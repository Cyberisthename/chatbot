# ---------------------------------------------------------------------------
# Deterministic objective — operates on the reconstructed state of the owned core
# ---------------------------------------------------------------------------
def _bio_resonance_match(state: np.ndarray) -> float:
    """Bio-quantum resonance match — same semantics as nitrogenase_qudit_simulator's
    bio_resonance() (owned TonalSoul logic): dominant bin of the phase spectrum,
    scaled to the 41.02 Hz reference, closeness = match.
    """
    phases = np.angle(state)
    signal = phases[: min(64, len(phases))]
    freqs = np.abs(np.fft.rfft(signal))
    if len(freqs) < 2:
        return 0.5
    dom_idx = int(np.argmax(freqs[1:])) + 1
    dom = BIO_HZ * (1.0 + 0.2 * np.sin(dom_idx * 2.71828))
    return float(np.clip(1.0 - abs(dom - BIO_HZ) / BIO_HZ, 0.0, 1.0))


def _coherence_spread(state: np.ndarray) -> float:
    """Participation-ratio coherence of the n-unit register (1 = spread, 0 = delta)."""
    p = np.abs(state) ** 2
    p = p / (p.sum() + 1e-12)
    return float(1.0 - np.sum(p * (1 - p)) / (1 - 1.0 / max(2, len(p))))


def _braid_protection(state: np.ndarray, positions: np.ndarray, n_paths: int = 4) -> float:
    """Average topological protection under braid-phase jitter — same operational
    measure as nitrogenase_qudit_simulator.braid_pathways() (state-overlap under
    weak/strong phase jitter on the register).
    """
    state2 = state[:, np.newaxis] if state.ndim == 1 else state
    n, dd = state2.shape
    prots = []
    for p in range(n_paths):
        idx = np.linspace(0, n - 1, max(4, n // n_paths)).astype(int)
        rng = np.random.RandomState(2100 + p)
        eps_s = rng.uniform(-0.16, 0.16, (len(idx), dd))
        num_s = 0.0
        wsum = 0.0
        for i, k in np.ndindex(len(idx), dd):
            w = abs(state2[idx[i], k]) ** 2
            wsum += w
            num_s += w * np.exp(1j * eps_s[i, k])
        prots.append(float(abs(num_s) / (wsum + 1e-12)))
    return float(np.clip(np.mean(prots), 0.0, 1.0))


def objective_from_state(state, positions) -> dict:
    bio = _bio_resonance_match(state)
    coh = _coherence_spread(state)
    braid = _braid_protection(state, positions)
    return {
        "objective_combined": float(0.4 * bio + 0.3 * coh + 0.3 * braid),
        "bio_resonance_match": bio,
        "coherence_spread": coh,
        "braid_protection": braid,
    }


class Evaluator:
    """One reusable compressor instance == fixed-topology slice of the family.

    NB: this mirrors the conservative restriction already used by
    ERROR_BOUND_PROOF.md Thm 3's empirical confirmation (fixed topology slice).
    The base state is pinned to the documented deterministic fallback so results
    are identical regardless of CWD / qvgpu-train artifacts.
    """

    def __init__(self, n: int = N_QUI):
        self.comp = FractalBraidSeedCompressor(n_effective_qubits=n, seed=OWNER_SEED, qudit_dim=2)
        # Pin the deterministic base (reproducible across machines/CWDs)
        self.comp.base_state = np.exp(2j * np.pi * np.linspace(0, 1, n)) / np.sqrt(n)

    def evaluate(self, seed3):
        self.comp.seed = tuple(float(x) for x in seed3)
        state, positions, metrics = self.comp.reconstruct()
        m = objective_from_state(state, positions)
        m["mse"] = float(metrics["reconstruction_mse"])
        m["fold_factor"] = metrics["geometric_fold_factor"]
        return m

    def maximize(self, seed3):
        return -self.evaluate(seed3)["objective_combined"]



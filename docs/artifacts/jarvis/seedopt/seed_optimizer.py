def coord_descent(ev, budget: int, restarts: int = 8, step0: float = 0.5):
    rng = np.random.default_rng(RNG_SEED + 1)
    per = max(budget // restarts, 30)
    best_x, best_v = None, -1e18
    hist = []
    for r in range(restarts):
        x = BOX_LO + rng.uniform(size=3) * (BOX_HI - BOX_LO)
        v = ev.evaluate(x)["objective_combined"]
        used = 1
        step = step0
        while used < per:
            improved = False
            for i in range(3):
                for sgn in (1.0, -1.0):
                    if used >= per:
                        break
                    cand = np.clip(x + sgn * step * np.eye(3)[i], BOX_LO, BOX_HI)
                    cv = ev.evaluate(cand)["objective_combined"]
                    used += 1
                    if cv > v:
                        x, v = cand, cv
                        improved = True
            step *= 0.62
            if not improved:
                break
        if v > best_v:
            best_v, best_x = v, x.copy()
        hist.append((r, float(v)))
    return best_x, float(best_v), hist, used


def nelder_mead(ev, budget: int, alpha=1.0, gamma=2.0, rho=0.5, sigma=0.5):
    rng = np.random.default_rng(RNG_SEED + 2)
    sim = np.vstack([BOX_LO + rng.uniform(size=3) * (BOX_HI - BOX_LO) for _ in range(4)])
    vals = np.array([ev.evaluate(s)["objective_combined"] for s in sim])
    used = 4
    hist = []
    while used < budget:
        order = np.argsort(vals)
        sim, vals = sim[order], vals[order]
        centroid = sim[:-1].mean(axis=0)
        xr = np.clip(centroid + alpha * (centroid - sim[-1]), BOX_LO, BOX_HI)
        vr = ev.evaluate(xr)["objective_combined"]
        used += 1
        if vr >= vals[0]:
            xe = np.clip(centroid + gamma * (xr - centroid), BOX_LO, BOX_HI)
            ve = ev.evaluate(xe)["objective_combined"]
            used += 1
            sim[-1] = xe if ve >= vr else xr
            vals[-1] = max(ve, vr)
        elif vr < vals[-2]:
            xc = np.clip(centroid + rho * (sim[-1] - centroid), BOX_LO, BOX_HI)
            vc = ev.evaluate(xc)["objective_combined"]
            used += 1
            if vc > vals[-1]:
                sim[-1], vals[-1] = xc, vc
            else:
                sim[1:] = sim[1:] + sigma * (sim[0] - sim[1:])
                vals[1:] = [ev.evaluate(si)["objective_combined"] for si in sim[1:]]
                used += len(sim[1:])
        else:
            sim[-1], vals[-1] = xr, vr
        hist.append((used, float(vals.max())))
    order = np.argsort(vals)
    return sim[order[-1]].copy(), float(vals[order[-1]]), hist, used


def cma_es(ev, budget: int, lam=12, sigma0=1.5):
    """(mu/mu_w, lambda)-CMA-ES, pure numpy. Standard log-normal step update."""
    rng = np.random.default_rng(RNG_SEED + 3)
    n = 3
    mu = lam // 2
    w = np.log(mu + 0.5) - np.log(np.arange(1, mu + 1))
    w = w / w.sum()
    mueff = 1.0 / np.sum(w ** 2)
    cc = 4.0 / (n + 4.0)
    cs = (mueff + 2.0) / (n + mueff + 5.0)
    damps = 1.0 + 2.0 * max(0.0, math.sqrt((mueff - 1.0) / (n + 1.0)) - 1.0) + cs
    ccov = (2.0 / (n + math.sqrt(2.0)) ** 2) * (1.0 + 1.0 / mueff)
    xmean = BOX_LO + rng.uniform(size=n) * (BOX_HI - BOX_LO)
    sigma = sigma0
    pc = np.zeros(n)
    B = np.eye(n)
    D = np.ones(n)
    C = np.eye(n)
    used = 0
    hist = []
    best_v, best_x = -1e18, xmean.copy()
    while used < budget:
        A = B @ np.diag(D)
        z = rng.normal(size=(lam, n))
        Y = xmean + sigma * (z @ A.T)
        Y = np.clip(Y, BOX_LO, BOX_HI)
        V = np.array([ev.evaluate(y)["objective_combined"] for y in Y])
        used += lam
        order = np.argsort(-V)
        Y, V = Y[order], V[order]
        yw = Y[:mu].T @ w
        if V[0] > best_v:
            best_v, best_x = V[0], Y[0].copy()
        xold = xmean.copy()
        xmean = yw
        pc = (1 - cc) * pc + math.sqrt(cc * (2 - cc) * mueff) * (xmean - xold) / (sigma + 1e-12)
        ps = (1 - cs) * pc + math.sqrt(cs * (2 - cs) * mueff) * (xmean - xold) / (sigma + 1e-12)
        hs = float(np.linalg.norm(ps) / math.sqrt(1 - (1 - cs) ** (2 * used / lam)) < 1.4 + 2.0 / (n + 1.0))
        C = (1 - ccov) * C + ccov * (np.outer(pc, pc) + (1 - hs) * cc * (2 - cc) * C)
        eig, V = np.linalg.eigh(C)
        eig = np.clip(eig, 1e-12, None)
        B = V
        D = np.sqrt(eig)
        sigma = sigma * math.exp((cs / damps) * (np.linalg.norm(ps) / (math.sqrt(n) * (1 - 1 / (4 * n) + 1 / (21 * n * n))) - 1)) if hs == 1 else sigma * math.exp((cs / damps) * (np.linalg.norm(ps) - 1.0) / 2.0)
        hist.append((used, float(best_v)))
    return best_x, float(best_v), hist, used



# Landscape characterization (measured, honest)
# ---------------------------------------------------------------------------
def characterize_landscape(ev, n_samples: int, n_probes: int = 40):
    rng = np.random.default_rng(RNG_SEED)
    unit = rng.uniform(size=(n_samples, 3))
    seeds = BOX_LO + unit * (BOX_HI - BOX_LO)
    vals = np.array([ev.evaluate(s)["objective_combined"] for s in seeds])
    # local Lipschitz / roughness probes: small random moves around random bases
    diag = float(np.linalg.norm(BOX_HI - BOX_LO))
    base_idx = rng.choice(n_samples, size=n_probes, replace=False)
    slop = []
    imp = 0
    for bi in base_idx:
        b = seeds[bi]
        vb = vals[bi]
        for _ in range(4):
            d = rng.normal(size=3)
            d = d / (np.linalg.norm(d) + 1e-12) * (0.02 * diag)
            nb = np.clip(b + d, BOX_LO, BOX_HI)
            vn = ev.evaluate(nb)["objective_combined"]
            slop.append(abs(vn - vb) / (np.linalg.norm(nb - b) + 1e-12))
            imp += float(vn > vb)
    return {
        "samples": int(n_samples),
        "mean": float(vals.mean()),
        "std": float(vals.std()),
        "min": float(vals.min()),
        "max": float(vals.max()),
        "median": float(np.median(vals)),
        "p10": float(np.percentile(vals, 10)),
        "p90": float(np.percentile(vals, 90)),
        "local_slope_median": float(np.median(slop)),
        "small_move_improve_fraction": imp / (n_probes * 4),
        "readout": ("landscape is glassy at small scale (improve fraction ~0.5): population/restart methods advised" if imp / (n_probes * 4) < 0.45 else ("landscape featureless at probed scale" if imp / (n_probes * 4) < 0.55 else "landscape smooth-ish at probed scale")),
    }



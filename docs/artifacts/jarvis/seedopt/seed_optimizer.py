def run(fast: bool = False):
    budget = 384 if fast else 2048
    n_land = 160 if fast else 512
    seed0_metrics = None
    ev = Evaluator()
    t0 = time.time()

    # baseline: owner seed on the same objective
    base = ev.evaluate(OWNER_SEED)
    seed0_metrics = base

    # 1) landscape
    landscape = characterize_landscape(ev, n_land)
    landscape["budget_flag"] = "fast (CI)" if fast else "full"

    # 2) optimizer comparison (shared budget)
    strategies = {}
    for name, fn in (("coordinate_descent", coord_descent),
                     ("nelder_mead", nelder_mead),
                     ("cma_es", cma_es)):
        xs, vs, hist, used = fn(ev, budget=budget)
        extra = ev.evaluate(xs)
        strategies[name] = {
            "seed": [round(float(v), 8) for v in xs],
            "objective_combined": vs,
            "evals_used": int(used),
            "improvement_over_owner": float(vs - base["objective_combined"]),
            "metrics": {k: round(float(v), 6) for k, v in extra.items()},
            "converged_by_evals_1pct": _evals_to_1pct(hist, vs),
        }

    # 3) overall best seed (winner across strategies)
    winner = max(strategies, key=lambda k: strategies[k]["objective_combined"])
    best_seed = strategies[winner]["seed"]

    # --- hard post-check: MSE=0, bit-identical determinism at n=32 ---
    chk = []
    for _ in range(2):
        c = FractalBraidSeedCompressor(n_effective_qubits=N_QUI, seed=tuple(best_seed), qudit_dim=2)
        c.base_state = np.exp(2j * np.pi * np.linspace(0, 1, N_QUI)) / np.sqrt(N_QUI)
        st, po, mt = c.reconstruct()
        chk.append((st, po, mt))
    bit_identical = bool(np.array_equal(chk[0][0], chk[1][0]) and np.array_equal(chk[0][1], chk[1][1]))
    post_check = {
        "n": N_QUI,
        "bit_identical_across_reconstructions": bit_identical,
        "mse_reported_by_core": float(chk[0][2]["reconstruction_mse"]),
        "mse_reconstruction_reenforced": 0.0,
        "pass": bool(bit_identical and chk[0][2]["reconstruction_mse"] == 0.0),
        "theorem3_note": "family unchanged: optimizer searched elements of the ≤3-parameter family (Thm 3); exactness by construction preserved.",
    }

    results = {
        "task": "core-jarvis-1-variational-seed-optimizer",
        "date": "2026-09-18",
        "n_qudits": N_QUI,
        "objective": "combined = 0.4*bio_resonance_match + 0.3*coherence_spread + 0.3*braid_protection (maximize)",
        "owner_seed_baseline": {"seed": list(OWNER_SEED), "metrics": {k: round(float(v), 6) for k, v in base.items()}},
        "landscape": landscape,
        "budget_per_strategy": int(budget),
        "strategies": strategies,
        "winner": winner,
        "optimized_seed": [round(float(v), 8) for v in best_seed],
        "optimized_seed_metrics": {k: round(float(v), 6) for k, v in strategies[winner]["metrics"].items()},
        "exactness_post_check": post_check,
        "runtime_seconds": round(time.time() - t0, 2),
        "tags": {"landscape_stats": "(a) measured", "optimizer_comparison": "(a) measured",
                 "interpretation": "(b) interpretation", "cap_speculation": "(c) speculation"},
    }
    (OUT / "seedopt_results.json").write_text(json.dumps(results, indent=2))
    _write_md(results)
    print(json.dumps(results, indent=2))
    return results


def _evals_to_1pct(hist, best_final):
    if not hist:
        return None
    thr = best_final - 0.01 * (best_final if best_final > 0 else 1.0)
    for used, v in hist:
        if v >= thr:
            return int(used)
    return hist[-1][0]


